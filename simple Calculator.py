# MAKING A CALCULATOR :=
 
num1= int(input("ENTER FIRST NUMBER :"))
num2=int(input("ENTER SECOUND NUMBER :"))
operation = input("ENTER YOUR OPERATION :")

if(operation=="+"):
    print(num1+num2)

elif(operation == "-"):
    print(num1-num2)

elif(operation=="*"):
    print(num1*num2)

elif(operation=="%"):
    print(num1%num2)

elif(operation=="/"):
    print(num1/num2)
else:
    print("INVALID OPERATION")
    print("Please try again")
















